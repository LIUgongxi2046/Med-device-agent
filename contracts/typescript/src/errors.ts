export type ErrorCode = typeof ERROR_CODES[number]
type SchemaErrorCode = Extract<ErrorCode, 'SCHEMA_INVALID' | 'SCHEMA_UNSUPPORTED'>
const registered: ReadonlySet<string> = new Set(ERROR_CODES)

export class SchemaRejection extends Error {
  readonly code: SchemaErrorCode

  constructor(code: SchemaErrorCode) {
    if (code !== 'SCHEMA_INVALID' && code !== 'SCHEMA_UNSUPPORTED') throw new Error('Schema 拒绝类型不符合发布集合')
    super(code === 'SCHEMA_INVALID' ? 'SCHEMA_VALIDATION_FAILED' : 'SCHEMA_UNSUPPORTED')
    this.name = 'SchemaRejection'
    this.code = code
    Object.freeze(this)
  }
}

export function parseErrorCode(value: unknown): ErrorCode {
  if (typeof value !== 'string' || !registered.has(value)) throw new SchemaRejection('SCHEMA_UNSUPPORTED')
  return value as ErrorCode
}
