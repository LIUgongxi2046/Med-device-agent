class UnsupportedSchemaError(ValueError):
    def __init__(self):
        super().__init__("SCHEMA_UNSUPPORTED")

    @property
    def code(self) -> ErrorCode:
        return ErrorCode.SCHEMA_UNSUPPORTED


class SchemaValidationError(ValidationError):
    def __init__(self, *, validator, path):
        super().__init__("SCHEMA_VALIDATION_FAILED", validator=validator, path=path)

    @property
    def code(self) -> ErrorCode:
        return ErrorCode.SCHEMA_INVALID


def parse_error_code(value: object) -> ErrorCode:
    if not isinstance(value, str) or value not in ErrorCode._value2member_map_:
        raise UnsupportedSchemaError()
    return ErrorCode(value)
