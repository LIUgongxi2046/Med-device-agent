import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'

const owner = JSON.parse(readFileSync(new URL('../../.implementation-work/runtime/owner-credentials.json', import.meta.url)))
const workflow=JSON.parse(readFileSync(new URL('../../.implementation-work/runtime/acceptance-template-workflow.json',import.meta.url)))
const browser = await chromium.launch({ channel:'chrome',headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(90000)
const results = []
try {
  page.on('response',response=>{const path=new URL(response.url()).pathname;if(['/auth/login','/auth/csrf','/api/session','/api/rule-versions'].includes(path))console.log('服务读取',response.status(),path)})
  page.on('requestfailed',request=>console.error('请求失败',new URL(request.url()).pathname,request.failure()?.errorText))
  page.on('pageerror',failure=>console.error('页面错误',failure.message))
  console.log('打开登录页面')
  await page.goto('http://127.0.0.1:18083/access')
  console.log('读取登录表单')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill(owner.username)
  await page.getByLabel('密码', { exact: true }).fill(owner.password)
  await page.getByRole('button', { name: '登录工作台', exact: true }).click()
  console.log('登录表单已提交')
  await page.waitForURL(url => url.pathname === '/index')
  console.log('登录通过')
  await page.goto('http://127.0.0.1:18083/operations')
  await page.getByRole('heading', { name: '评测与运营', exact: true }).waitFor()
  const navigation = page.getByRole('navigation', { name: '评测与运营分区' })
  for (const name of ['质量评测', '反馈改进', '用量与成本', '审计记录']) assert.ok(await navigation.getByRole('link', { name, exact: true }).count())
  console.log('运营分区通过')
  await page.getByRole('button', { name: '读取统计', exact: true }).click()
  await page.locator('[data-operations-report]').waitFor()
  for (const label of ['登记调用', '结果采纳率', '审查退回率', '调用与计费记录']) assert.ok((await page.locator('main').innerText()).includes(label))
  results.push({ check: 'PR03-01', state: 'PASS' })
  console.log('真实统计通过')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出当前统计', exact: true }).click()
  const download = await downloadPromise
  assert.match(download.suggestedFilename(), /business-operations.*\.csv$/)
  await download.saveAs(new URL('../../.implementation-work/prototype-operations.csv', import.meta.url).pathname)
  results.push({ check: 'PR03-04', state: 'PASS' })
  await navigation.getByRole('link', { name: '反馈改进', exact: true }).click()
  await page.getByRole('heading', { name: '反馈与版本改进', exact: true }).waitFor()
  const directoryResponse=page.waitForResponse(response=>response.request().method()==='GET'&&new URL(response.url()).pathname==='/api/rule-versions')
  await page.getByRole('button', { name: '登记反馈', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '登记改进反馈', exact: true })
  await dialog.waitFor()
  const directory=await directoryResponse
  assert.equal(directory.status(),200,await directory.text())
  await dialog.getByRole('combobox').focus()
  await dialog.getByRole('combobox').press('ArrowDown')
  const version = page.getByRole('option',{name:workflow.rule_input.reason,exact:true})
  try { await version.waitFor() } catch(failure) { console.error('关联版本提示',await dialog.innerText());console.error('目录选项',await page.locator('.el-select-dropdown__item').allTextContents());throw failure }
  await version.click()
  const issue = '原型还原验收 ' + Date.now() + '：规则页面应同时提供业务名称、检查对象、处理条件及审查记录。'
  await dialog.getByRole('textbox', { name: '问题依据', exact: true }).fill(issue)
  const createResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/business-operations/knowledge-feedback')
  await dialog.getByRole('button', { name: '保存反馈', exact: true }).click()
  const created = await createResponse
  assert.equal(created.status(), 200, await created.text())
  const creation = (await created.json()).data
  const originalRequest = created.request()
  const originalHeaders = await originalRequest.allHeaders()
  const requestHeaders = Object.fromEntries(Object.entries(originalHeaders).filter(([name]) => ['origin', 'x-schema-version', 'x-context-revision', 'idempotency-key', 'x-csrf-token', 'x-xsrf-token', 'content-type'].includes(name)))
  writeFileSync(new URL('../../.implementation-work/prototype-feedback-operation.json',import.meta.url),JSON.stringify({receipt:creation,key:originalHeaders['idempotency-key'],body:originalRequest.postDataJSON()}),{mode:0o600})
  const lookup = await page.request.get('http://127.0.0.1:18083/api/business-operations/knowledge-feedback/operations/' + originalHeaders['idempotency-key'], { headers: requestHeaders,timeout:90000 })
  assert.equal(lookup.status(), 200, await lookup.text())
  assert.deepEqual((await lookup.json()).data.receipt, creation)
  const replay = await page.request.post(originalRequest.url(), { headers: requestHeaders, data: originalRequest.postDataJSON(),timeout:90000 })
  assert.equal(replay.status(), 200, await replay.text())
  assert.deepEqual((await replay.json()).data, creation)
  const conflict = await page.request.post(originalRequest.url(), { headers: requestHeaders, data: { ...originalRequest.postDataJSON(), reason: issue + ' 修改完整参数' },timeout:90000 })
  assert.equal(conflict.status(), 409, await conflict.text())
  assert.equal((await conflict.json()).code, 'IDEMPOTENCY_CONFLICT')
  results.push({ check: 'PR03-05', state: 'PASS', feedback_id: creation.feedback_id })
  await dialog.waitFor({ state: 'hidden' })
  const row = page.getByRole('row').filter({ hasText: issue })
  await row.waitFor()
  results.push({ check: 'PR03-02', state: 'PASS' })
  await row.getByRole('button', { name: '处理记录', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '反馈处理记录', exact: true })
  await drawer.getByText(issue, { exact: true }).first().waitFor()
  await drawer.getByRole('combobox').focus()
  await drawer.getByRole('combobox').press('ArrowDown')
  await page.getByRole('option', { name: '不采纳反馈', exact: true }).click()
  await drawer.getByRole('textbox', { name: '决定依据', exact: true }).fill('本次反馈用于验证实际登记与处理记录，原型功能开发继续由当前任务管理。')
  const decisionResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/rejections'))
  await drawer.getByRole('button', { name: '保存处理决定', exact: true }).click()
  const decided = await decisionResponse
  assert.equal(decided.status(), 200, await decided.text())
  await drawer.getByText('不采纳反馈').count()
  await drawer.locator('.el-timeline-item').filter({ hasText: '未采纳' }).waitFor()
  results.push({ check: 'PR03-03', state: 'PASS' })
  writeFileSync(new URL('../../.implementation-work/prototype-operations-checks.json', import.meta.url), JSON.stringify({ verified_at: new Date().toISOString(), results }, null, 2))
  console.log(JSON.stringify(results))
} catch (failure) {
  console.error('当前页面', page.url())
  console.error('页面提示', await page.getByRole('alert').allTextContents())
  console.error('登录状态',await page.locator('.login-form .el-form-item__error,.el-message__content').allTextContents())
  throw new Error(failure.message.split('\n')[0])
} finally {
  await browser.close()
}
