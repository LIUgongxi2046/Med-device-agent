import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'
const root = new URL('../../', import.meta.url)
const owner = JSON.parse(readFileSync(new URL('.implementation-work/runtime/owner-credentials.json', root)))
const workflow = JSON.parse(readFileSync(new URL('.implementation-work/runtime/acceptance-template-workflow.json', root)))
const browser = await chromium.launch({ channel:'chrome',headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(120000)
const evidence = { checks: [], screenshots: false }
try {
  page.on('console',message=>{if(message.type()==='error')console.error('浏览器错误',message.text().slice(0,500))})
  page.on('pageerror',failure=>console.error('页面错误',failure.message))
  await page.goto('http://127.0.0.1:18083/access')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill(owner.username)
  await page.getByLabel('密码', { exact: true }).fill(owner.password)
  await page.getByRole('button', { name: '登录工作台', exact: true }).click()
  await page.waitForURL(url => url.pathname === '/index')
  await page.evaluate(()=>{const config=document.getElementById('app').__vue_app__.config,original=config.errorHandler;config.errorHandler=(failure,instance,info)=>{console.error('原型验收错误',failure.stack??failure.message,info);return original(failure,instance,info)}})
  console.log('模板验收登录通过')
  await page.goto('http://127.0.0.1:18083/templates')
  const types = page.getByRole('navigation', { name: '模板类型' })
  await types.waitFor()
  console.log('模板类型导航通过')
  assert.equal(await types.getByRole('button').count(), 14)
  evidence.checks.push({ id: 'PR01-01', state: 'PASS' })
  const templateId = workflow.template_version ?? workflow.template_id
  assert.match(templateId, /^[a-f0-9-]{36}$/)
  await page.goto('http://127.0.0.1:18083/templates/' + templateId + '/approval')
  await page.getByRole('heading', { name: '章节与生成规则', exact: true }).waitFor()
  await page.evaluate(()=>{const config=document.getElementById('app').__vue_app__.config,original=config.errorHandler;config.errorHandler=(failure,instance,info)=>{console.error('章节配置错误',failure.stack??failure.message,info);return original(failure,instance,info)}})
  await page.getByRole('button', { name: '修改章节配置', exact: true }).click()
  const chapters = page.locator('[data-template-chapter-workspace]')
  await chapters.waitFor()
  await chapters.getByRole('button', { name: '配置章节', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '章节配置', exact: true })
  await dialog.getByRole('textbox', { name: '检查要求', exact: true }).fill('SIMULATION 原型验收：保留完整章节依据，确认文字、来源版本及人工核查要求。')
  await dialog.getByRole('button', { name: '确认章节配置', exact: true }).click()
  console.log('章节配置已确认')
  await page.getByRole('tab', { name: '全部字段', exact: true }).click()
  await page.getByRole('button', { name: '编辑字段定义', exact: true }).click()
  const fieldDialog = page.getByRole('dialog', { name: '字段定义编辑', exact: true })
  await fieldDialog.getByRole('button', { name: '编辑本项定义', exact: true }).first().click()
  await fieldDialog.getByRole('combobox', { name: '所属章节', exact: true }).waitFor({ timeout: 10000 })
  await fieldDialog.getByRole('spinbutton', { name: '长度上限', exact: true }).waitFor()
  await fieldDialog.getByRole('textbox', { name: '字段说明', exact: true }).fill('SIMULATION 字段业务配置：填写待整理资料的实际名称，保留完整范围依据。')
  await fieldDialog.getByRole('button', { name: '确认当前定义', exact: true }).click()
  await fieldDialog.getByRole('button', { name: '采用本次定义修改', exact: true }).click()
  await fieldDialog.waitFor({ state: 'hidden' })
  await page.getByRole('textbox', { name: '创建或修订理由', exact: true }).fill('SIMULATION 原型章节配置真实修订 ' + Date.now())
  await page.getByText('已经核查全部目录、字段、附件、条件、依据及版式；本次只保存草稿', { exact: true }).click()
  assert.equal(await page.getByRole('checkbox', { name: '已经核查全部目录、字段、附件、条件、依据及版式；本次只保存草稿', exact: true }).isChecked(),true)
  const responsePromise = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/template-versions')
  await page.getByRole('button', { name: '保存模板草稿', exact: true }).click()
  const response = await responsePromise
  assert.equal(response.status(), 201, await response.text())
  const result = await response.json()
  assert.notEqual(result.data.template.template_version, templateId)
  assert.equal(result.data.template.base_version.version_id, templateId)
  assert.ok(result.data.template.content.nodes.some(node => node.content_requirements.some(requirement => requirement.includes('SIMULATION 原型验收'))))
  assert.ok(result.data.template.content.field_definitions.some(field => field.description.includes('SIMULATION 字段业务配置')))
  evidence.checks.push({ id: 'PR01-02', state: 'PASS', template_version: result.data.template.template_version })
  await page.getByRole('link', { name: '打开人工审查', exact: true }).click()
  await page.locator('[data-template-preview]').waitFor()
  await page.getByRole('heading', { name: '章节与生成规则', exact: true }).waitFor()
  assert.ok((await page.locator('[data-template-preview]').innerText()).includes('SIMULATION 原型验收'))
  await page.getByRole('button', { name: '登记人工决定', exact: true }).click()
  const approval = page.getByRole('dialog', { name: '确认模板人工决定', exact: true })
  await approval.getByRole('combobox').focus()
  await approval.getByRole('combobox').press('ArrowDown')
  await page.getByRole('option', { name: '核准', exact: true }).click()
  await approval.getByRole('textbox', { name: '决定理由', exact: true }).fill('SIMULATION 已核查修改后的章节要求及全部实际目录、字段、附件、字体、版式和规则依据，仅用于本地编辑流程验证。')
  await approval.getByText('已经核查完整目录、字段、附件、规则、版式和获授权依据', { exact: true }).click()
  const approvalResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/template-versions/' + result.data.template.template_version + '/approval-decisions')
  await approval.getByRole('button', { name: '确认登记决定', exact: true }).click()
  const approved = await approvalResponse
  assert.equal(approved.status(), 200, await approved.text())
  assert.equal((await approved.json()).data.status, 'APPROVED')
  await page.getByText('原模板决定已完成并核查', { exact: true }).waitFor()
  await page.reload()
  await page.locator('[data-template-preview]').waitFor()
  assert.ok((await page.locator('[data-template-preview]').innerText()).includes('已核准'))
  evidence.checks.push({ id: 'PR01-04', state: 'PASS', template_version: result.data.template.template_version })
  evidence.verified_at = new Date().toISOString()
  writeFileSync(new URL('.implementation-work/prototype-template-checks.json', root), JSON.stringify(evidence, null, 2))
  console.log(JSON.stringify(evidence))
} catch(failure){console.error('当前页面',page.url());console.error('标题',await page.locator('h1,h2').allTextContents());console.error('提示',await page.getByRole('alert').allTextContents());throw new Error(failure.message.split('\n')[0])} finally { await browser.close() }
