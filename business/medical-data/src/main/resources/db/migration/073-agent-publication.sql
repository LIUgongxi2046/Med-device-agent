CREATE TABLE evaluation_acceptance_policy_decision (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NULL,
 draft_id CHAR(36) CHARACTER SET ascii NOT NULL,
 decision_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 draft_resource_id CHAR(36) CHARACTER SET ascii NOT NULL,
 draft_kind VARCHAR(32) NOT NULL,
 decision_kind VARCHAR(32) NOT NULL,
 schema_version VARCHAR(20) CHARACTER SET ascii NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(32) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(tenant_id,draft_id),
 UNIQUE KEY uq_eap_decision(tenant_id,decision_id),
 CONSTRAINT fk_eap_draft FOREIGN KEY(tenant_id,project_key,draft_resource_id,draft_id,draft_kind) REFERENCES agent_publication_record(tenant_id,project_key,resource_id,record_id,kind),
 CONSTRAINT fk_eap_decision FOREIGN KEY(tenant_id,project_key,draft_id,decision_id,decision_kind) REFERENCES agent_publication_record(tenant_id,project_key,resource_id,record_id,kind),
 CONSTRAINT fk_eap_project FOREIGN KEY(tenant_id,project_id) REFERENCES project(tenant_id,project_id),
 CONSTRAINT fk_eap_creator FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 CONSTRAINT ck_eap_identity CHECK(draft_resource_id=draft_id AND draft_kind='POLICY_DRAFT' AND decision_kind='POLICY'),
 CONSTRAINT ck_eap_schema CHECK(schema_version='1.0.0'),
 CONSTRAINT ck_eap_hash CHECK(schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$'),
 CONSTRAINT ck_eap_class CHECK(classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
