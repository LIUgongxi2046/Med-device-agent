 project_id CHAR(36) CHARACTER SET ascii NOT NULL,
 write_id CHAR(36) CHARACTER SET ascii NOT NULL,
 operation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 artifact_id CHAR(36) CHARACTER SET ascii NOT NULL,
 execution_id CHAR(36) CHARACTER SET ascii NOT NULL,
 evaluation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 sample_id CHAR(36) CHARACTER SET ascii NOT NULL,
 repeat_index INT UNSIGNED NOT NULL,
 node_kind VARCHAR(8) CHARACTER SET ascii NOT NULL,
 context_version CHAR(36) CHARACTER SET ascii NOT NULL,
 context_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 source_input_version CHAR(36) CHARACTER SET ascii NOT NULL,
 source_input_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 canonical_intent LONGTEXT NOT NULL,
 intent_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 canonical_payload LONGTEXT NOT NULL,
 payload_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 audit_id CHAR(36) CHARACTER SET ascii NOT NULL,
 event_id CHAR(36) CHARACTER SET ascii NOT NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 PRIMARY KEY (tenant_id,write_id),
 UNIQUE KEY uq_eval_plan_operation (tenant_id,operation_id),
 UNIQUE KEY uq_eval_plan_artifact (tenant_id,artifact_id),
 UNIQUE KEY uq_eval_plan_key (tenant_id,created_by,idempotency_key),
 UNIQUE KEY uq_eval_plan_node (tenant_id,execution_id,sample_id,repeat_index,node_kind),
 UNIQUE KEY uq_eval_plan_project (tenant_id,project_id,write_id),
 UNIQUE KEY uq_eval_plan_identity (tenant_id,write_id,operation_id,artifact_id),
 FOREIGN KEY (tenant_id,project_id,execution_id) REFERENCES formal_evaluation_execution(tenant_id,project_id,execution_id),
 FOREIGN KEY (tenant_id,execution_id) REFERENCES formal_evaluation_execution_context(tenant_id,execution_id),
 FOREIGN KEY (tenant_id,context_version,context_sha256) REFERENCES formal_evaluation_context_version(tenant_id,version_id,content_sha256),
 FOREIGN KEY (tenant_id,evaluation_id) REFERENCES version_registry(tenant_id,version_id),
 FOREIGN KEY (tenant_id,source_input_version,source_input_sha256) REFERENCES version_registry(tenant_id,version_id,content_sha256),
 FOREIGN KEY (tenant_id,operation_id) REFERENCES operation_record(tenant_id,operation_id),
 FOREIGN KEY (tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 FOREIGN KEY (tenant_id,audit_id) REFERENCES audit_event(tenant_id,audit_id),
 FOREIGN KEY (tenant_id,event_id) REFERENCES outbox_event(tenant_id,event_id),
 CHECK (repeat_index<100 AND node_kind='N01'),
 CHECK (JSON_VALID(canonical_intent) AND JSON_VALID(canonical_payload)),
 CHECK (CHAR_LENGTH(idempotency_key) BETWEEN 16 AND 128 AND idempotency_key REGEXP '^[!-~]+$'),
 CHECK (schema_version='1.0.0'),
 CHECK (context_sha256 REGEXP '^[a-f0-9]{64}$' AND source_input_sha256 REGEXP '^[a-f0-9]{64}$' AND request_sha256 REGEXP '^[a-f0-9]{64}$' AND intent_sha256 REGEXP '^[a-f0-9]{64}$' AND payload_sha256 REGEXP '^[a-f0-9]{64}$' AND schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$'),
 CHECK (classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

