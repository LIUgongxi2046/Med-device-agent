-- Immutable fixed-document comparison records only. No jobs, checks, seeds, grants or credentials.
--changeset medical-agent:069-01-document-comparison-intent dbms:mysql runInTransaction:false failOnError:true
CREATE TABLE document_comparison_intent (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NOT NULL,
 comparison_id CHAR(36) CHARACTER SET ascii NOT NULL,
 operation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 manifest_id CHAR(36) CHARACTER SET ascii NOT NULL,
 access_set_id CHAR(36) CHARACTER SET ascii NOT NULL,
 artifact_id CHAR(36) CHARACTER SET ascii NOT NULL,
 write_id CHAR(36) CHARACTER SET ascii NOT NULL,
 start_event_id CHAR(36) CHARACTER SET ascii NOT NULL,
 document_id CHAR(36) CHARACTER SET ascii NOT NULL,
 left_revision CHAR(36) CHARACTER SET ascii NOT NULL,
 right_revision CHAR(36) CHARACTER SET ascii NOT NULL,
 request_context VARCHAR(20) CHARACTER SET ascii NOT NULL,
 request_session CHAR(36) CHARACTER SET ascii NOT NULL,
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 canonical_request LONGTEXT NOT NULL,
 request_body_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 operation_request_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 input_manifest LONGTEXT NOT NULL,
 input_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 dependency_manifest LONGTEXT NOT NULL,
 dependency_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 canonical_core LONGTEXT NOT NULL,
 core_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 schema_version VARCHAR(16) CHARACTER SET ascii NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 deadline DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (project_id) STORED,
 PRIMARY KEY(tenant_id,comparison_id),
 UNIQUE KEY uq_comparison_intent_actor_key(tenant_id,created_by,idempotency_key),
 UNIQUE KEY uq_comparison_intent_operation(tenant_id,operation_id),
 UNIQUE KEY uq_comparison_intent_artifact(tenant_id,artifact_id),
 UNIQUE KEY uq_comparison_intent_write(tenant_id,write_id),
 UNIQUE KEY uq_comparison_intent_start_event(tenant_id,start_event_id),
 UNIQUE KEY uq_comparison_intent_attempt(tenant_id,project_id,comparison_id,operation_id,write_id),
 UNIQUE KEY uq_comparison_intent_complete(tenant_id,project_id,comparison_id,operation_id,artifact_id,core_sha256),
 FOREIGN KEY(tenant_id,project_id,document_id,left_revision) REFERENCES document_revision_meta(tenant_id,project_id,document_id,document_revision),
 FOREIGN KEY(tenant_id,project_id,document_id,right_revision) REFERENCES document_revision_meta(tenant_id,project_id,document_id,document_revision),
 FOREIGN KEY(tenant_id,manifest_id,input_sha256) REFERENCES version_registry(tenant_id,version_id,content_sha256),
 FOREIGN KEY(tenant_id,project_key,access_set_id,dependency_sha256) REFERENCES dependency_access_manifest(tenant_id,project_key,access_set_id,manifest_sha256),
 FOREIGN KEY(tenant_id,operation_id) REFERENCES operation_record(tenant_id,operation_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 CHECK(deadline>created_at),
 CHECK(request_context REGEXP '^[0-9]+$'),
 CHECK(CHAR_LENGTH(idempotency_key) BETWEEN 16 AND 128 AND idempotency_key REGEXP '^[!-~]+$'),
 CHECK(schema_version='1.0.0'),
 CHECK(classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(JSON_VALID(canonical_request) AND JSON_VALID(input_manifest) AND JSON_VALID(dependency_manifest) AND JSON_VALID(canonical_core)),
 CHECK(request_body_sha256 REGEXP '^[a-f0-9]{64}$' AND operation_request_sha256 REGEXP '^[a-f0-9]{64}$' AND input_sha256 REGEXP '^[a-f0-9]{64}$' AND dependency_sha256 REGEXP '^[a-f0-9]{64}$' AND core_sha256 REGEXP '^[a-f0-9]{64}$' AND schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

