CREATE TABLE model_verification_input_preparation (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NOT NULL,
 artifact_id CHAR(36) CHARACTER SET ascii NOT NULL,
 source_id CHAR(36) CHARACTER SET ascii NOT NULL,
 source_version CHAR(36) CHARACTER SET ascii NOT NULL,
 rights_revision CHAR(36) CHARACTER SET ascii NOT NULL,
 purpose VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 access_set_id CHAR(36) CHARACTER SET ascii NOT NULL,
 dependency_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 document_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 object_version VARCHAR(256) NOT NULL,
 schema_ref VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 document_schema_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 canonical_document LONGTEXT NOT NULL,
 canonical_request LONGTEXT NOT NULL,
 request_body_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 operation_request_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_context VARCHAR(20) CHARACTER SET ascii NOT NULL,
 request_session CHAR(36) CHARACTER SET ascii NOT NULL,
 authorization_json LONGTEXT NOT NULL,
 authorization_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 receipt_json LONGTEXT NOT NULL,
 operation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 audit_id CHAR(36) CHARACTER SET ascii NOT NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 resource_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 artifact_kind VARCHAR(32) NOT NULL,
 snapshot_id CHAR(36) CHARACTER SET ascii NOT NULL,
 snapshot_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 profile_revision CHAR(36) CHARACTER SET ascii NOT NULL,
 model_revision CHAR(36) CHARACTER SET ascii NOT NULL,
 config_id CHAR(36) CHARACTER SET ascii NOT NULL,
 artifact_manifest CHAR(64) CHARACTER SET ascii NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 PRIMARY KEY(tenant_id,artifact_id),
 UNIQUE KEY uq_verification_input_operation(tenant_id,operation_id),
 UNIQUE KEY uq_verification_input_request(tenant_id,created_by,idempotency_key),
 UNIQUE KEY uq_verification_input_audit(tenant_id,audit_id),
 FOREIGN KEY(tenant_id,project_key,artifact_id,document_sha256,object_version) REFERENCES artifact(tenant_id,project_key,artifact_id,sha256,object_version),
 FOREIGN KEY(tenant_id,project_key,artifact_id,resource_kind,source_id,schema_ref,document_schema_sha256,access_set_id,dependency_sha256) REFERENCES artifact_content_binding(tenant_id,project_key,artifact_id,resource_kind,resource_id,schema_ref,schema_document_sha256,dependency_access_set_id,dependency_manifest_sha256),
 FOREIGN KEY(tenant_id,source_id,source_version) REFERENCES source_version(tenant_id,source_id,source_version),
 FOREIGN KEY(tenant_id,source_version,rights_revision) REFERENCES rights_revision(tenant_id,source_version,rights_revision),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 FOREIGN KEY(tenant_id,operation_id) REFERENCES operation_record(tenant_id,operation_id),
 FOREIGN KEY(tenant_id,audit_id) REFERENCES audit_event(tenant_id,audit_id),
 FOREIGN KEY(tenant_id,operation_id) REFERENCES outbox_event(tenant_id,event_id),
 CHECK(project_id IS NOT NULL AND resource_kind='SOURCE' AND artifact_kind='EXACT_INPUT'),
 CHECK(schema_version='1.0.0' AND schema_ref='urn:medical:simulation-execution:1.0.0#/$defs/ExactInput'),
 CHECK(classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(snapshot_sha256 REGEXP '^[a-f0-9]{64}$' AND artifact_manifest REGEXP '^[a-f0-9]{64}$'),
 CHECK(purpose IN ('DOCUMENT_BODY','MODEL_VERIFICATION')),
 CHECK(purpose REGEXP '^[A-Z][A-Z0-9_]{0,63}$' AND idempotency_key REGEXP '^[A-Za-z0-9._:-]{16,128}$' AND request_context REGEXP '^[1-9][0-9]{0,19}$'),
 CHECK(dependency_sha256 REGEXP '^[a-f0-9]{64}$' AND document_sha256 REGEXP '^[a-f0-9]{64}$' AND document_schema_sha256 REGEXP '^[a-f0-9]{64}$' AND request_body_sha256 REGEXP '^[a-f0-9]{64}$' AND operation_request_sha256 REGEXP '^[a-f0-9]{64}$' AND authorization_sha256 REGEXP '^[a-f0-9]{64}$' AND schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$'),
 CHECK(JSON_VALID(canonical_document) AND JSON_TYPE(CAST(canonical_document AS JSON))='OBJECT' AND JSON_VALID(canonical_request) AND JSON_TYPE(CAST(canonical_request AS JSON))='OBJECT' AND JSON_VALID(authorization_json) AND JSON_TYPE(CAST(authorization_json AS JSON))='OBJECT' AND JSON_VALID(receipt_json) AND JSON_TYPE(CAST(receipt_json AS JSON))='OBJECT'),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.artifact_kind')) <=> artifact_kind AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.input_schema_ref')) <=> schema_ref AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.input_schema_sha256')) <=> document_schema_sha256),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.source.version_id')) <=> source_version AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.source.content_sha256')) <=> document_sha256 AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.rights_revision')) <=> rights_revision AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.business_purpose')) <=> purpose AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.created_by')) <=> created_by),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.source.version_id')) <=> source_version),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.source.content_sha256')) <=> document_sha256),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.rights_revision')) <=> rights_revision),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.business_purpose')) <=> purpose),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.artifact.version_id')) <=> artifact_id),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.artifact.content_sha256')) <=> document_sha256),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.operation_id')) <=> operation_id),
 CHECK(JSON_LENGTH(canonical_request)=8 AND JSON_LENGTH(receipt_json)=17),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.project_id')) <=> project_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.project_id')) <=> project_id),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.profile_revision')) <=> profile_revision AND JSON_UNQUOTE(JSON_EXTRACT(canonical_request,'$.model_config_revision')) <=> model_revision),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.scope_snapshot_basis.version_id')) <=> snapshot_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.scope_snapshot_basis.content_sha256')) <=> snapshot_sha256),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.exact_input.artifact_id')) <=> artifact_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.exact_input.sha256')) <=> document_sha256),
 CHECK(OCTET_LENGTH(canonical_request)<=8192 AND OCTET_LENGTH(canonical_document)<=2097152 AND OCTET_LENGTH(authorization_json)<=4194304 AND OCTET_LENGTH(receipt_json)<=16384),
 FOREIGN KEY(tenant_id,project_id,snapshot_id) REFERENCES scope_snapshot(tenant_id,project_id,snapshot_id),
 FOREIGN KEY(tenant_id,profile_revision) REFERENCES version_registry(tenant_id,version_id),
 FOREIGN KEY(tenant_id,model_revision) REFERENCES version_registry(tenant_id,version_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
