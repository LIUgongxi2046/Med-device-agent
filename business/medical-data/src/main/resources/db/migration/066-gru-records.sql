CREATE TABLE gru_message_record (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NOT NULL,
 conversation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 message_id CHAR(36) CHARACTER SET ascii NOT NULL,
 message_sequence BIGINT UNSIGNED NOT NULL,
 canonical_request_json LONGTEXT NOT NULL,
 request_body_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 operation_request_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 receipt_json LONGTEXT NOT NULL,
 intent VARCHAR(24) NOT NULL,
 execution_state VARCHAR(24) NOT NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 PRIMARY KEY(tenant_id,message_id),
 UNIQUE KEY uq_gru_message_sequence(tenant_id,conversation_id,message_sequence),
 FOREIGN KEY(tenant_id,project_id,conversation_id,message_id) REFERENCES conversation_message(tenant_id,project_id,conversation_id,message_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 CHECK(message_sequence BETWEEN 2 AND 501),
 CHECK(schema_version='1.0.0'),
 CHECK(execution_state='NOT_EXECUTED'),
 CHECK(intent IN ('QUERY','RETRIEVE','CHECK','PROPOSE_EDIT')),
 CHECK(classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(JSON_VALID(canonical_request_json) AND JSON_VALID(receipt_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
