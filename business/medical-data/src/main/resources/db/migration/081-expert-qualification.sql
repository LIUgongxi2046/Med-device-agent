CREATE TABLE expert_qualification_record (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NULL,
 record_id CHAR(36) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 qualification_id CHAR(36) CHARACTER SET ascii NOT NULL,
 operation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 request_body_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_context VARCHAR(20) CHARACTER SET ascii NOT NULL,
 request_session CHAR(36) CHARACTER SET ascii NOT NULL,
 content_json LONGTEXT NOT NULL,
 content_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 authorizations_json LONGTEXT NOT NULL,
 authorizations_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 receipt_json LONGTEXT NOT NULL,
 receipt_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 audit_id CHAR(36) CHARACTER SET ascii NOT NULL,
 event_id CHAR(36) CHARACTER SET ascii NOT NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 PRIMARY KEY(tenant_id,record_id),
 FOREIGN KEY(tenant_id,project_id) REFERENCES project(tenant_id,project_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 UNIQUE KEY uq_eq_record_scope(tenant_id,project_key,qualification_id,record_id,kind,content_sha256),
 UNIQUE KEY uq_eq_record_qualification(tenant_id,qualification_id,record_id,kind,content_sha256),
 UNIQUE KEY uq_eq_record_decision(tenant_id,qualification_id,record_id,kind),
 UNIQUE KEY uq_eq_record_scoped_decision(tenant_id,project_key,qualification_id,record_id,kind),
 UNIQUE KEY uq_eq_record_operation(tenant_id,operation_id),
 UNIQUE KEY uq_eq_record_key(tenant_id,created_by,kind,idempotency_key),
 UNIQUE KEY uq_eq_record_audit(tenant_id,audit_id),
 UNIQUE KEY uq_eq_record_event(tenant_id,event_id),
 FOREIGN KEY(tenant_id,record_id,content_sha256) REFERENCES version_registry(tenant_id,version_id,content_sha256),
 FOREIGN KEY(tenant_id,operation_id) REFERENCES operation_record(tenant_id,operation_id),
 FOREIGN KEY(tenant_id,audit_id) REFERENCES audit_event(tenant_id,audit_id),
 FOREIGN KEY(tenant_id,event_id) REFERENCES outbox_event(tenant_id,event_id),
 CHECK(kind IN ('AUTHOR','APPROVE','REJECT','REVOKE','SCORE_BIND')),
 CHECK(idempotency_key REGEXP '^[A-Za-z0-9._:-]{16,128}$' AND request_context REGEXP '^[1-9][0-9]{0,19}$'),
 CHECK(JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.operation_id')) <=> operation_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.kind')) <=> kind AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.record.version_id')) <=> record_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.record.content_sha256')) <=> content_sha256 AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.qualification.version_id')) <=> qualification_id AND JSON_UNQUOTE(JSON_EXTRACT(receipt_json,'$.created_by')) <=> created_by),
 CHECK(schema_version='1.0.0' AND classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(request_sha256 REGEXP '^[a-f0-9]{64}$' AND request_body_sha256 REGEXP '^[a-f0-9]{64}$' AND content_sha256 REGEXP '^[a-f0-9]{64}$' AND authorizations_sha256 REGEXP '^[a-f0-9]{64}$' AND receipt_sha256 REGEXP '^[a-f0-9]{64}$' AND schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$'),
 CHECK(JSON_VALID(request_json) AND JSON_TYPE(CAST(request_json AS JSON))='OBJECT' AND JSON_VALID(content_json) AND JSON_TYPE(CAST(content_json AS JSON))='OBJECT' AND JSON_VALID(authorizations_json) AND JSON_TYPE(CAST(authorizations_json AS JSON))='OBJECT' AND JSON_VALID(receipt_json) AND JSON_TYPE(CAST(receipt_json AS JSON))='OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

