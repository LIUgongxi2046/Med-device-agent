CREATE TABLE expert_qualification_state (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NULL,
 qualification_id CHAR(36) CHARACTER SET ascii NOT NULL,
 status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 decision_id CHAR(36) CHARACTER SET ascii NULL,
 decision_kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 PRIMARY KEY(tenant_id,qualification_id),
 FOREIGN KEY(tenant_id,project_id) REFERENCES project(tenant_id,project_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 FOREIGN KEY(tenant_id,project_key,qualification_id) REFERENCES expert_qualification(tenant_id,project_key,qualification_id),
 FOREIGN KEY(tenant_id,project_key,qualification_id,decision_id,decision_kind) REFERENCES expert_qualification_record(tenant_id,project_key,qualification_id,record_id,kind),
 CHECK(status IN ('DRAFT','APPROVED','REJECTED','REVOKED') AND revision BETWEEN 1 AND 3 AND updated_at>=created_at),
 CHECK((status='DRAFT' AND revision=1 AND decision_id IS NULL AND decision_kind IS NULL AND updated_at=created_at) OR (status='APPROVED' AND revision=2 AND decision_id IS NOT NULL AND decision_kind='APPROVE') OR (status='REJECTED' AND revision=2 AND decision_id IS NOT NULL AND decision_kind='REJECT') OR (status='REVOKED' AND revision=3 AND decision_id IS NOT NULL AND decision_kind='REVOKE')),
 CHECK(schema_version='1.0.0' AND classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

