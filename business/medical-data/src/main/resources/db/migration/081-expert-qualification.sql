CREATE TABLE expert_qualification (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NULL,
 qualification_id CHAR(36) CHARACTER SET ascii NOT NULL,
 content_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 expert_id CHAR(36) CHARACTER SET ascii NOT NULL,
 domain VARCHAR(128) NOT NULL,
 purpose VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 dimensions_json LONGTEXT NOT NULL,
 valid_from DATETIME(6) NOT NULL,
 valid_to DATETIME(6) NOT NULL,
 schema_version VARCHAR(32) NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(24) NOT NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 author_record_id CHAR(36) CHARACTER SET ascii NOT NULL,
 author_kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PRIMARY KEY(tenant_id,qualification_id),
 FOREIGN KEY(tenant_id,project_id) REFERENCES project(tenant_id,project_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 UNIQUE KEY uq_eq_qualification_hash(tenant_id,qualification_id,content_sha256),
 UNIQUE KEY uq_eq_qualification_scope(tenant_id,project_key,qualification_id),
 FOREIGN KEY(tenant_id,project_key,qualification_id,author_record_id,author_kind,content_sha256) REFERENCES expert_qualification_record(tenant_id,project_key,qualification_id,record_id,kind,content_sha256),
 FOREIGN KEY(tenant_id,expert_id) REFERENCES tenant_member(tenant_id,user_id),
 CHECK(author_record_id=qualification_id AND author_kind='AUTHOR' AND valid_to>valid_from AND CHAR_LENGTH(domain)>0 AND purpose REGEXP '^[A-Z][A-Z0-9_]{0,63}$'),
 CHECK(JSON_VALID(dimensions_json) AND JSON_TYPE(CAST(dimensions_json AS JSON))='ARRAY' AND JSON_LENGTH(dimensions_json) BETWEEN 1 AND 12),
 CHECK(schema_version='1.0.0' AND classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH')),
 CHECK(content_sha256 REGEXP '^[a-f0-9]{64}$' AND schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

