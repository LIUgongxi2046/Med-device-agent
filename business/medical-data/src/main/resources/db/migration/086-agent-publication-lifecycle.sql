CREATE TABLE formal_agent_acceptance (
 tenant_id CHAR(36) CHARACTER SET ascii NOT NULL,
 project_id CHAR(36) CHARACTER SET ascii NULL,
 project_key VARCHAR(36) CHARACTER SET ascii GENERATED ALWAYS AS (COALESCE(project_id,'ENTERPRISE')) STORED,
 acceptance_id CHAR(36) CHARACTER SET ascii NOT NULL,
 candidate_version_id CHAR(36) CHARACTER SET ascii NOT NULL,
 candidate_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 evaluation_id CHAR(36) CHARACTER SET ascii NOT NULL,
 evaluation_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 release_id CHAR(36) CHARACTER SET ascii NOT NULL,
 manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 content_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 decision VARCHAR(16) CHARACTER SET ascii NOT NULL,
 journal_kind VARCHAR(32) NOT NULL,
 schema_version VARCHAR(20) CHARACTER SET ascii NOT NULL,
 schema_manifest_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL,
 classification VARCHAR(32) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(tenant_id,acceptance_id),
 UNIQUE KEY uq_faa_hash(tenant_id,acceptance_id,content_sha256),
 UNIQUE KEY uq_faa_release(tenant_id,release_id),
 FOREIGN KEY(tenant_id,project_key,candidate_version_id,candidate_sha256) REFERENCES formal_agent_candidate_binding(tenant_id,project_key,version_id,content_sha256),
 FOREIGN KEY(tenant_id,evaluation_id,evaluation_sha256) REFERENCES version_registry(tenant_id,version_id,content_sha256),
 FOREIGN KEY(tenant_id,project_key,candidate_version_id,acceptance_id,journal_kind) REFERENCES agent_publication_record(tenant_id,project_key,resource_id,record_id,kind),
 FOREIGN KEY(tenant_id,acceptance_id,content_sha256) REFERENCES version_registry(tenant_id,version_id,content_sha256),
 CHECK(decision IN ('ACCEPT','REJECT') AND journal_kind='ACCEPTANCE'),
 CHECK(candidate_sha256 REGEXP '^[a-f0-9]{64}$' AND evaluation_sha256 REGEXP '^[a-f0-9]{64}$' AND manifest_sha256 REGEXP '^[a-f0-9]{64}$' AND content_sha256 REGEXP '^[a-f0-9]{64}$'),
 FOREIGN KEY(tenant_id,project_id) REFERENCES project(tenant_id,project_id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES tenant_member(tenant_id,user_id),
 CHECK(schema_version='1.0.0'),
 CHECK(schema_manifest_sha256 REGEXP '^[a-f0-9]{64}$'),
 CHECK(classification IN ('PUBLIC','INTERNAL','RESTRICTED','PERSONAL_HEALTH'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
